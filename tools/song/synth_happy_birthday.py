"""Synthesizes an original music-box recording of the traditional Happy Birthday melody.

The melody is public domain. Every sample here is generated by this script, so
the recording is original and carries no third-party rights.

Usage: python tools/song/synth_happy_birthday.py
Needs: numpy, lameenc (pip install lameenc)
"""
from __future__ import annotations

import pathlib

import lameenc
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
RATE = 44100
BEAT = 0.62  # seconds per quarter note, 3/4 time

NOTE = {n: i for i, n in enumerate(["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"])}


def hz(name: str) -> float:
    return 440.0 * 2 ** ((NOTE[name[:-1]] + 12 * (int(name[-1]) + 1) - 69) / 12)


# (pitch, beats): the pick-up, then four phrases
MELODY = [
    ("G4", 0.75), ("G4", 0.25),
    ("A4", 1), ("G4", 1), ("C5", 1),
    ("B4", 2), ("G4", 0.75), ("G4", 0.25),
    ("A4", 1), ("G4", 1), ("D5", 1),
    ("C5", 2), ("G4", 0.75), ("G4", 0.25),
    ("G5", 1), ("E5", 1), ("C5", 1),
    ("B4", 1), ("A4", 1), ("F5", 0.75), ("F5", 0.25),
    ("E5", 1), ("C5", 1), ("D5", 1),
    ("C5", 3),
]

# One chord per bar, after the one-beat pick-up
CHORDS = [
    ["C3", "G3", "E4"], ["G2", "G3", "D4"], ["G2", "G3", "F4"], ["C3", "G3", "E4"],
    ["C3", "G3", "E4"], ["F2", "F3", "C4"], ["C3", "G3", "E4"], ["C3", "G3", "E4"],
]


def tone(freq: float, seconds: float, gain: float, soft: bool) -> np.ndarray:
    """A plucked chime: inharmonic partials, each fading at its own rate."""
    t = np.arange(int(seconds * RATE)) / RATE
    partials = [(1.0, 1.0, 1.5), (2.0, 0.34, 2.8), (3.01, 0.13, 4.5), (5.4, 0.05, 9.0)]
    if soft:
        partials = [(1.0, 1.0, 1.1), (2.0, 0.18, 2.2)]
    wave = np.zeros_like(t)
    for ratio, level, decay in partials:
        if freq * ratio < RATE / 2.2:
            wave += level * np.sin(2 * np.pi * freq * ratio * t) * np.exp(-decay * t)
    attack = np.minimum(t / (0.018 if soft else 0.004), 1)
    return wave * attack * gain


def mix(buffer: np.ndarray, part: np.ndarray, start: float) -> None:
    i = int(start * RATE)
    end = min(i + len(part), len(buffer))
    buffer[i:end] += part[: end - i]


def reverb(dry: np.ndarray) -> np.ndarray:
    """A short decaying echo network, enough to give the chime a room."""
    wet = np.zeros_like(dry)
    for delay, level in [(0.031, 0.32), (0.047, 0.27), (0.083, 0.21), (0.127, 0.16), (0.211, 0.10), (0.33, 0.06)]:
        n = int(delay * RATE)
        wet[n:] += dry[:-n] * level
    return wet


def render() -> np.ndarray:
    total = sum(b for _, b in MELODY) * BEAT + 3.6
    left = np.zeros(int(total * RATE))
    right = np.zeros_like(left)

    time = 0.6
    for pitch, beats in MELODY:
        note = tone(hz(pitch), 3.2, 0.40, soft=False)
        mix(left, note, time)
        mix(right, note, time + 0.0015)
        time += beats * BEAT

    # accompaniment enters on the first downbeat, a beat after the pick-up
    bar = 3 * BEAT
    for i, chord in enumerate(CHORDS):
        start = 0.6 + 1.0 * BEAT + i * bar
        final = i == len(CHORDS) - 1
        mix(left, tone(hz(chord[0]), 3.4, 0.22, soft=True), start)
        mix(right, tone(hz(chord[0]), 3.4, 0.22, soft=True), start)
        for beat, pitch in ((1, chord[1]), (2, chord[2])):
            if final:
                break
            mix(left, tone(hz(pitch), 2.2, 0.085, soft=True), start + beat * BEAT)
            mix(right, tone(hz(pitch), 2.2, 0.12, soft=True), start + beat * BEAT)
        if final:
            mix(left, tone(hz(chord[1]), 3.2, 0.1, soft=True), start)
            mix(right, tone(hz(chord[2]), 3.2, 0.11, soft=True), start)

    left, right = left + reverb(right), right + reverb(left)
    stereo = np.stack([left, right], 1)
    fade = np.minimum((len(stereo) - np.arange(len(stereo))) / (RATE * 1.0), 1)
    stereo *= fade[:, None]
    return stereo / np.abs(stereo).max() * 0.86


def main() -> None:
    pcm = (render() * 32767).astype(np.int16)
    encoder = lameenc.Encoder()
    encoder.set_bit_rate(96)
    encoder.set_in_sample_rate(RATE)
    encoder.set_channels(2)
    encoder.set_quality(2)
    data = encoder.encode(pcm.tobytes()) + encoder.flush()
    out = ROOT / "public/audio/happy-birthday.mp3"
    out.write_bytes(data)
    print(out, len(data) // 1024, "KB,", round(len(pcm) / RATE, 1), "s")


if __name__ == "__main__":
    main()
